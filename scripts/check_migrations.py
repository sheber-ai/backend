"""pre-commit: reject migrations not created by autogenerate."""

import sys
from pathlib import Path

AUTOGENERATE_MARKER = "# ### commands auto generated by Alembic"


def main(filenames: list[str]) -> int:
    manual = [name for name in filenames if AUTOGENERATE_MARKER not in Path(name).read_text(encoding="utf-8")]
    for name in manual:
        sys.stderr.write(f'{name}: not autogenerated. Use make migration m="..."\n')
    return 1 if manual else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
